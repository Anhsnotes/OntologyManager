"""Export the ontology as Markdown for LLM prompts and human readers.

The .ttl stays the source of truth. This file is generated from it, so it can
never drift: `ontman check` fails if the committed Markdown is out of date.

Design choices for LLM use:
- Terms are shown as prefixed names (`:Loan`) exactly as they must appear in SPARQL.
- Every term carries its plain-language definition (rdfs:comment).
- OWL logic is rendered in readable Manchester-style text, not raw triples.
- Reasoning behaviour (transitive, inverse, defined classes) is spelled out,
  so the model knows what the reasoner will infer and does not try to do it itself.
- Competency questions become worked examples (question → SPARQL) for few-shot prompting.
- Output is deterministic (sorted), so git diffs of the Markdown are meaningful too.
"""

from __future__ import annotations

from pathlib import Path

from rdflib import OWL, RDF, RDFS, XSD, BNode, Graph, Literal, URIRef
from rdflib.collection import Collection

from . import graphs
from .checks import query_headers

HEADER_NOTE = "<!-- Generated by `ontman export-md` from {src}. Do not edit by hand. -->"


class _Renderer:
    def __init__(self, g: Graph, ns: str):
        self.g, self.ns = g, ns

    # ------------------------------------------------------------ names
    def name(self, t) -> str:
        if isinstance(t, URIRef):
            s = str(t)
            if s.startswith(self.ns):
                return f"`:{s[len(self.ns):]}`"
            if s.startswith(str(XSD)):
                return f"`xsd:{s[len(str(XSD)):]}`"
            return f"`{t.n3(self.g.namespace_manager)}`"
        if isinstance(t, BNode):
            return self.expr(t)
        return f'"{t}"'

    def label(self, t) -> str | None:
        v = self.g.value(t, RDFS.label)
        return str(v) if v else None

    def comment(self, t) -> str:
        # Prefer the definition that is not a deprecation note.
        comments = sorted(str(c) for c in self.g.objects(t, RDFS.comment))
        main = [c for c in comments if not c.lower().startswith("deprecated")]
        return (main or comments or [""])[0]

    # ------------------------------------------------------------ OWL expressions
    def _list(self, node) -> list:
        return list(Collection(self.g, node))

    def expr(self, node) -> str:
        """Render a class expression in readable, Manchester-like syntax."""
        g = self.g
        if isinstance(node, URIRef):
            return self.name(node)
        if (lst := g.value(node, OWL.intersectionOf)) is not None:
            return " **and** ".join(self._paren(x) for x in self._list(lst))
        if (lst := g.value(node, OWL.unionOf)) is not None:
            return " **or** ".join(self._paren(x) for x in self._list(lst))
        if (c := g.value(node, OWL.complementOf)) is not None:
            return f"**not** {self._paren(c)}"
        if (lst := g.value(node, OWL.oneOf)) is not None:
            return "one of {" + ", ".join(self.name(x) for x in self._list(lst)) + "}"
        prop = g.value(node, OWL.onProperty)
        if prop is not None:
            p = self.name(prop)
            for pred, word in ((OWL.someValuesFrom, "some"), (OWL.allValuesFrom, "only")):
                if (v := g.value(node, pred)) is not None:
                    return f"{p} **{word}** {self._paren(v)}"
            if (v := g.value(node, OWL.hasValue)) is not None:
                return f"{p} **value** {self.name(v)}"
            for preds, word in (((OWL.minCardinality, OWL.minQualifiedCardinality), "min"),
                                ((OWL.maxCardinality, OWL.maxQualifiedCardinality), "max"),
                                ((OWL.cardinality, OWL.qualifiedCardinality), "exactly")):
                for pred in preds:
                    if (n := g.value(node, pred)) is not None:
                        on = g.value(node, OWL.onClass)
                        return f"{p} **{word}** {n}" + (f" {self._paren(on)}" if on else "")
        return "(complex expression)"

    def _paren(self, node) -> str:
        s = self.expr(node)
        return f"({s})" if isinstance(node, BNode) and " **" in s else s


def _deprecated(g: Graph, t) -> bool:
    return (t, OWL.deprecated, Literal(True)) in g


def _named(g: Graph, rdf_type) -> list[URIRef]:
    return sorted((s for s in g.subjects(RDF.type, rdf_type) if isinstance(s, URIRef)), key=str)


def export_markdown(g: Graph, ns: str, competency_dir: Path | None = None,
                    source_name: str = "src/ontology.ttl", examples: bool = True) -> str:
    r = _Renderer(g, ns)
    out: list[str] = [HEADER_NOTE.format(src=source_name), ""]

    # ------------------------------------------------------------ header
    onto = graphs.ontology_iri(g)
    title = (r.label(onto) if onto else None) or "Ontology"
    version = g.value(onto, OWL.versionInfo) if onto else None
    out.append(f"# {title}" + (f" (v{version})" if version else ""))
    if onto and (desc := r.comment(onto)):
        out += ["", desc]
    out += [
        "",
        "## How to use this vocabulary",
        "",
        "```sparql",
        f"PREFIX : <{ns}>",
        "PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>",
        "PREFIX xsd: <http://www.w3.org/2001/XMLSchema#>",
        "```",
        "",
        "- Use **only** the classes and properties listed here. Do not invent terms.",
        "- Do not use terms in the *Deprecated* section; use their replacements.",
        "- The query engine applies reasoning (see *What the reasoner infers*). "
        "Query for the general class and let the reasoner find subclasses; "
        "do not enumerate subclasses or follow transitive chains by hand.",
    ]

    classes = [c for c in _named(g, OWL.Class) if not _deprecated(g, c)]
    class_set = set(classes)

    # ------------------------------------------------------------ class hierarchy
    def defined_parents(c) -> set:
        """Named classes in `c ≡ A and B and ...`: c is necessarily a subclass of each."""
        out_ = set()
        for e in g.objects(c, OWL.equivalentClass):
            lst = g.value(e, OWL.intersectionOf) if isinstance(e, BNode) else None
            if lst is not None:
                out_.update(x for x in Collection(g, lst) if isinstance(x, URIRef))
        return out_

    defined = {c for c in classes if any(True for _ in g.objects(c, OWL.equivalentClass))}
    parents = {c: sorted({p for p in g.objects(c, RDFS.subClassOf) if isinstance(p, URIRef)}
                         | defined_parents(c), key=str) for c in classes}
    parents = {c: [p for p in ps if p in class_set] for c, ps in parents.items()}
    children: dict = {c: [] for c in classes}
    for c, ps in parents.items():
        for p in ps:
            children[p].append(c)
    roots = [c for c in classes if not parents[c]]

    out += ["", "## Classes", ""]

    def tree(c, depth: int, via=None):
        lab = r.label(c)
        lab_txt = f" ({lab})" if lab and lab.lower() != str(c)[len(ns):].lower() else ""
        extra = " _(defined class, membership is inferred)_" if c in defined else ""
        others = [p for p in parents[c] if p != via]
        if via is not None and others:
            extra += " _(also under " + ", ".join(r.name(p) for p in others) + ")_"
        out.append(f"{'  ' * depth}- {r.name(c)}{lab_txt}: {r.comment(c)}{extra}")
        for ch in sorted(children[c], key=str):
            tree(ch, depth + 1, via=c)

    for c in roots:
        tree(c, 0)

    # ------------------------------------------------------------ class axioms
    axiom_lines = []
    for c in classes:
        lines = []
        for e in g.objects(c, OWL.equivalentClass):
            lines.append(f"defined as {r.expr(e)}")
        for e in g.objects(c, RDFS.subClassOf):
            if isinstance(e, BNode):
                lines.append(f"every instance is {r.expr(e)}")
        if lines:
            axiom_lines.append(f"- {r.name(c)}: " + "; ".join(sorted(lines)))
    disjoint = sorted({tuple(sorted((r.name(a), r.name(b))))
                       for a, b in g.subject_objects(OWL.disjointWith)
                       if a in class_set and b in class_set})
    if axiom_lines or disjoint:
        out += ["", "### Class rules", ""]
        out += axiom_lines
        for a, b in disjoint:
            out.append(f"- {a} and {b} are disjoint: nothing can be both.")

    # ------------------------------------------------------------ properties
    def prop_rows(kind) -> list[str]:
        rows = []
        for p in _named(g, kind):
            if _deprecated(g, p):
                continue
            dom = ", ".join(r.name(d) for d in sorted(g.objects(p, RDFS.domain), key=str)) or "any"
            rng = ", ".join(r.name(x) for x in sorted(g.objects(p, RDFS.range), key=str)) or "any"
            notes = []
            types = set(g.objects(p, RDF.type))
            for t, word in ((OWL.TransitiveProperty, "transitive"), (OWL.SymmetricProperty, "symmetric"),
                            (OWL.FunctionalProperty, "functional")):
                if t in types:
                    notes.append(word)
            invs = set(g.objects(p, OWL.inverseOf)) | set(g.subjects(OWL.inverseOf, p))
            notes += [f"inverse of {r.name(i)}" for i in sorted(invs, key=str)]
            notes += [f"sub-property of {r.name(s)}" for s in sorted(g.objects(p, RDFS.subPropertyOf), key=str)]
            rows.append(f"| {r.name(p)} | {dom} → {rng} | {', '.join(notes)} | {r.comment(p)} |")
        return rows

    for title_, kind in (("Relationships (object properties)", OWL.ObjectProperty),
                         ("Attributes (data properties)", OWL.DatatypeProperty)):
        rows = prop_rows(kind)
        if rows:
            out += ["", f"## {title_}", "", "| Property | Domain → Range | Characteristics | Meaning |",
                    "|---|---|---|---|", *rows]

    # ------------------------------------------------------------ reasoning notes
    notes = []
    for c in classes:
        if any(True for _ in g.objects(c, OWL.equivalentClass)):
            notes.append(f"- Anything matching the definition of {r.name(c)} is classified as {r.name(c)} "
                         "automatically. Data never asserts it; just query `?x a "
                         f":{str(c)[len(ns):]}`.")
    for p in _named(g, OWL.TransitiveProperty):
        n = f":{str(p)[len(ns):]}"
        notes.append(f"- {r.name(p)} is transitive: if A {n} B and B {n} C, then A {n} C. "
                     f"Query `?a {n} ?c` directly, no property paths needed.")
    seen = set()
    for a, b in sorted(g.subject_objects(OWL.inverseOf), key=lambda t: (str(t[0]), str(t[1]))):
        if (b, a) in seen:
            continue
        seen.add((a, b))
        notes.append(f"- {r.name(a)} and {r.name(b)} are inverses: stating one implies the other.")
    if roots:
        notes.append("- Subclasses inherit: an instance of a subclass is also an instance of every "
                     "class above it in the hierarchy.")
    if any(True for _ in g.subject_objects(RDFS.domain)):
        notes.append("- Domains and ranges infer types: using a property implies its subject is in "
                     "the domain and its object is in the range. They do **not** validate data.")
    if notes:
        out += ["", "## What the reasoner infers", "", *notes]

    # ------------------------------------------------------------ deprecated
    dep = [t for t in sorted(g.subjects(OWL.deprecated, Literal(True)), key=str) if isinstance(t, URIRef)]
    if dep:
        out += ["", "## Deprecated (do not use)", ""]
        for t in dep:
            repl = [r.name(x) for x in g.objects(t, graphs.DCTERMS.isReplacedBy)]
            out.append(f"- {r.name(t)}" + (f" → use {', '.join(sorted(repl))}" if repl else ""))

    # ------------------------------------------------------------ examples
    if examples and competency_dir and competency_dir.exists():
        files = sorted(competency_dir.glob("*.rq"))
        if files:
            out += ["", "## Example questions and SPARQL", ""]
            for f in files:
                text = f.read_text()
                q = query_headers(text).get("question", f.stem)
                body = "\n".join(line for line in text.splitlines() if not line.startswith("#")).strip()
                out += [f"**{q}**", "", "```sparql", body, "```", ""]
            out.pop()

    return "\n".join(out) + "\n"
